/**
 * Scratchpad:
 * 
 * Example: 
 *  0 ->     '0' -> [0]
 *  1 ->     '1' -> [0, 1]
 *  2 ->    '10' -> [0, 1, 1]
 *  3 ->    '11' -> [0, 1, 1, 2]
 *  4 ->   '100' -> [0, 1, 1, 2, 1]
 *  5 ->   '101' -> [0, 1, 1, 2, 1, 2]
 *  6 ->   '110' -> [0, 1, 1, 2, 1, 2, 2]
 *  7 ->   '111' -> [0, 1, 1, 2, 1, 2, 2, 3]
 *  8 ->  '1000' -> [0, 1, 1, 2, 1, 2, 2, 3, 1]
 *  9 ->  '1001' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2]
 * 10 ->  '1010' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2]
 * 11 ->  '1011' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3]
 * 12 ->  '1100' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2]
 * 13 ->  '1101' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2, 3]
 * 14 ->  '1110' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2, 3, 3]
 * 15 ->  '1111' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2, 3, 3, 4]
 * 16 -> '10000' -> [0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2, 3, 3, 4, 1]
 */

/**
 * @param {number} n
 * @return {number[]}
 */
export default function bitCounting(n: number): number[] {
  const result: number[] = [];
  for(let i=0; i<=n; i++) {
    if(i % 2 === 0) {
      result.push(result[i / 2]);
    } else {
      result.push(result[i - 1] + 1);
    }
  }

  return result;
}
